function getSongContentHtml(song) {
  if (song.blocks && song.blocks.length) return renderContentBlocks(song.blocks, '#E7D19C') || '<p class="muted">No story shared yet for this song.</p>';
  const legacy = [];
  if (song.about) legacy.push({ type: 'text', heading: 'About', content: song.about });
  if (song.thoughts) legacy.push({ type: 'text', heading: 'Thoughts', content: song.thoughts });
  if (song.behindTheScenes) legacy.push({ type: 'text', heading: 'Behind the Scenes', content: song.behindTheScenes });
  if (song.Miscellaneous) legacy.push({ type: 'text', heading: 'Miscellaneous', content: song.Miscellaneous });
  if (!legacy.length) return '<p class="muted">No story shared yet for this song.</p>';
  return renderContentBlocks(legacy, '#E7D19C');
}

function setCover(imgEl, emojiEl, song) {
  if (song.coverImg) { imgEl.src = song.coverImg; imgEl.classList.remove('hidden'); emojiEl.classList.add('hidden'); }
  else { imgEl.classList.add('hidden'); emojiEl.classList.remove('hidden'); emojiEl.textContent = song.cover || '🎵'; }
}

function openSong(key) {
  const song = SONGS[key];
  if (!song || !song.src) return;
  currentSongKey = key;
  if (songAudio.src !== new URL(song.src, location.href).href) { songAudio.src = song.src; songAudio.load(); }
  songAudio.play().catch(() => {});
  $('ovTitle').textContent = song.name;
  $('ovArtist').textContent = song.artist;
  setCover($('ovCoverImg'), $('ovCoverEmoji'), song);
  $('bpTitle').textContent = song.name;
  $('bpArtist').textContent = song.artist;
  setCover($('bpCover'), $('bpEmoji'), song);
  showBottomPlayer();
  $('ovBlocks').innerHTML = getSongContentHtml(song);

  const creditsWrap = $('ovCreditsWrap'), creditsEl = $('ovCredits');
  const credits = song.credits || [];
  if (credits.length) {
    creditsWrap.classList.remove('hidden');
    creditsEl.innerHTML = credits.map(c => {
      const person = c.personId && personData[c.personId] ? personData[c.personId] : null;
      const displayName = (person ? person.name : c.name) || 'Unknown';
      let avatarHtml = '<i class="fas fa-user" style="font-size:12px;color:var(--text-secondary)"></i>';
      if (person) {
        const [jpg, png] = avatarPair(person.avatar, c.personId);
        avatarHtml = `<img loading="lazy" decoding="async" src="${esc(jpg)}" alt="${esc(displayName)}" onerror="this.onerror=null;this.src='${esc(png)}';">`;
      }
      const nameHtml = person
        ? `<button type="button" class="credit-name" onclick="closeOverlay();setTimeout(()=>openPersonOverlay('${c.personId}'),250)">${esc(displayName)}<i class="fas fa-arrow-up-right-from-square"></i></button>`
        : `<span class="credit-name">${esc(displayName)}</span>`;
      const linksHtml = person && (person.links || []).length ? `<div class="credit-links">${person.links.map(l => `<a href="${esc(l.url)}" target="_blank" rel="noopener" title="${esc(l.name)}" aria-label="${esc(l.name)}"><i class="${l.icon}"></i></a>`).join('')}</div>` : '';
      return `<div class="credit-row"><div class="credit-avatar">${avatarHtml}</div><div style="flex:1;min-width:0">${nameHtml}<div class="credit-role">${esc(c.role || '')}</div>${linksHtml}</div></div>`;
    }).join('');
  } else { creditsWrap.classList.add('hidden'); creditsEl.innerHTML = ''; }

  const streamWrap = $('ovStreaming');
  const platforms = songPlatforms(song);
  streamWrap.innerHTML = platforms.length ? platforms.map(k => {
    const m = STREAMING_META[k];
    return `<a class="stream-btn" href="${ARTIST_PAGES[k]}" target="_blank" rel="noopener" style="background:${m.bg};color:${m.text}${m.border ? ';border:1px solid ' + m.border : ''}"><i class="${platformIcons[k] || 'fas fa-play'}"></i><span>${m.label}</span></a>`;
  }).join('') : '<span class="muted" style="font-size:13px">Not available on any platform yet.</span>';

  $('songOverlay').classList.add('open');
  document.body.style.overflow = 'hidden';
  if ('mediaSession' in navigator) {
    navigator.mediaSession.metadata = new MediaMetadata({ title: song.name, artist: song.artist, artwork: song.coverImg ? [{ src: new URL(song.coverImg, location.href).href }] : [] });
    navigator.mediaSession.setActionHandler('play', () => songAudio.play());
    navigator.mediaSession.setActionHandler('pause', () => songAudio.pause());
    navigator.mediaSession.setActionHandler('seekbackward', () => seekAudio(-10));
    navigator.mediaSession.setActionHandler('seekforward', () => seekAudio(10));
  }
}
