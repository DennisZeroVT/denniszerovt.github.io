function handleDeepLinkHash() {
  const h = decodeURIComponent(location.hash.slice(1));
  if (!h) return false;
  let key = null;
  if (SONGS[h]) key = h;
  else if (h.startsWith('song-') && SONGS[h.slice(5)]) key = h.slice(5);
  if (key) { showPage('music', false); setTimeout(() => openSong(key), 150); return true; }
  return false;
}
window.addEventListener('hashchange', () => {
  const h = location.hash.slice(1);
  if (handleDeepLinkHash()) return;
  if (sectionIds.includes(h)) showPage(h, false);
});

